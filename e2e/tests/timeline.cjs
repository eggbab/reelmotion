// 컴퓨터(마우스·키보드)에서 새 타임라인: 바로 끌기, 끝 끌어 길이, 줄 누르기, 눈금 끌기, 막대(키보드), 확대·축소, 화살표 키
const { chromium } = require('playwright')
const { BASE, OUT } = require('../env.cjs')
;(async () => {
  const browser = await chromium.launch()
  const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'ko-KR' })).newPage()
  const results = []
  const errors = []
  const ok = (name, cond, extra = '') => results.push(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`)
  page.on('pageerror', (e) => errors.push(`pageerror ${String(e).slice(0, 200)}`))
  page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errors.push(`console ${m.text().slice(0, 200)}`))
  const block = (name) => page.locator(`.block[aria-label^="${name} "]`).first()
  const times = async (name) => {
    const [, start, end] = /([\d.]+)–([\d.]+)s/.exec(await block(name).getAttribute('aria-label'))
    return { start: Number(start), end: Number(end) }
  }
  const playTime = async () => Number(/^([\d.]+)s/.exec(await page.locator('.ed-time').innerText())[1])
  await page.goto(BASE + '/ko/app', { waitUntil: 'networkidle' })
  await page.locator('.samples button:not(.is-tall)').first().click()
  await page.waitForSelector('.block')
  await page.waitForFunction(() => document.querySelector('.ed-frame video')?.duration > 0)
  await page.waitForTimeout(400)
  const layout = await page.evaluate(() => {
    const r = (s) => document.querySelector(s).getBoundingClientRect()
    return { stageRight: Math.round(r('.ed-stage').right), panelLeft: Math.round(r('.ed-panel').left), timelineTop: Math.round(r('.timeline').top), stageBottom: Math.round(r('.ed-stage').bottom), fits: document.documentElement.scrollHeight <= window.innerHeight, sticky: getComputedStyle(document.querySelector('.ed-stage')).position }
  })
  ok('desktop layout unchanged: panel on the right, timeline under the preview, one screen', layout.panelLeft >= layout.stageRight - 1 && layout.timelineTop >= layout.stageBottom - 1 && layout.fits && layout.sticky !== 'sticky', JSON.stringify(layout))
  const area = await page.locator('.timeline__area').boundingBox()
  const pps = area.width / 10
  // 바로 끌기(고르지 않은 블록)
  const before = await times('이름표')
  let b = await block('이름표').boundingBox()
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width / 2 + 90, b.y + b.height / 2, { steps: 6 })
  await page.mouse.up()
  const moved = await times('이름표')
  ok('mouse drags a block right away', Math.abs(moved.start - before.start - 90 / pps) < 0.15, `${before.start}→${moved.start} (+${(90 / pps).toFixed(1)})`)
  ok('and selects it', await block('이름표').evaluate((el) => el.classList.contains('is-selected')))
  // 끝 끌기
  b = await block('이름표').boundingBox()
  await page.mouse.move(b.x + b.width - 3, b.y + b.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width - 3 - 45, b.y + b.height / 2, { steps: 5 })
  await page.mouse.up()
  const resized = await times('이름표')
  ok('dragging the end changes the length', Math.abs(resized.start - moved.start) < 0.05 && Math.abs(moved.end - resized.end - 45 / pps) < 0.15, `${JSON.stringify(moved)}→${JSON.stringify(resized)}`)
  // 살짝 누르기만 하면 그대로
  b = await block('제목').boundingBox()
  const t0 = await times('제목')
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width / 2 + 2, b.y + b.height / 2)
  await page.mouse.up()
  ok('a click with a tiny shake does not move the block', JSON.stringify(await times('제목')) === JSON.stringify(t0))
  // 화살표 키
  await block('제목').focus()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  ok('arrow keys nudge by 0.1s', Math.abs((await times('제목')).start - t0.start - 0.2) < 0.01, `${t0.start}→${(await times('제목')).start}`)
  // 빈 줄 누르기 → 위치 + 고르기 풀림
  await page.mouse.click(area.x + area.width * 0.8, area.y + area.height - 60 - 46)
  await page.waitForTimeout(200)
  ok('clicking an empty lane seeks and clears the selection', Math.abs((await playTime()) - 8) < 0.3 && (await page.locator('.block.is-selected').count()) === 0, `time ${await playTime()}`)
  // 눈금 끌기
  const ruler = await page.locator('.timeline__ruler').boundingBox()
  await page.mouse.move(ruler.x + 10, ruler.y + 10)
  await page.mouse.down()
  await page.mouse.move(ruler.x + ruler.width * 0.5, ruler.y + 10, { steps: 8 })
  const mid = await playTime()
  await page.mouse.up()
  ok('dragging on the ruler scrubs', Math.abs(mid - 5) < 0.3, `time ${mid}`)
  // 막대(키보드)
  await page.locator('.ed-seek').focus()
  const s0 = await playTime()
  for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(200)
  ok('seek bar works from the keyboard (0.1s a press)', Math.abs((await playTime()) - s0 - 0.3) < 0.11, `${s0}→${await playTime()}`)
  ok('seek bar has a name for screen readers', (await page.locator('.ed-seek').getAttribute('aria-label')) === '영상 위치 옮기기')
  // 확대·축소
  const zoomOut = page.locator('.timeline__zoom button').first()
  const zoomIn = page.locator('.timeline__zoom button').nth(1)
  ok('short video fits: zoom out is off', await zoomOut.isDisabled())
  await zoomIn.click()
  const wide = await page.locator('.timeline__scroller').evaluate((el) => ({ scroll: el.scrollWidth, client: el.clientWidth }))
  ok('zoom in makes it scroll', wide.scroll > wide.client * 1.4, JSON.stringify(wide))
  await zoomOut.click()
  const fit = await page.locator('.timeline__scroller').evaluate((el) => ({ scroll: el.scrollWidth, client: el.clientWidth }))
  ok('zoom out fits again', fit.scroll <= fit.client + 1, JSON.stringify(fit))
  await page.screenshot({ path: OUT + '/desk-timeline.png' })
  console.log(results.join('\n'))
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors')
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })
