// 말로 고치기: 우리 서버의 AI 가 그래픽을 고치고(글·숫자·스타일·더하기·지우기), 되돌리기, 딴 얘기에는 고치지 않고 답만. AI 서버(assist)가 떠 있어야 한다.
const { chromium } = require('playwright')
const { BASE, OUT } = require('../env.cjs')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'ko-KR' })
  const errors = []
  page.on('pageerror', (e) => errors.push(String(e).slice(0, 200)))
  page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errors.push(m.text().slice(0, 200)))
  const results = []
  const ok = (name, cond, extra = '') => results.push(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`)
  await page.goto(`${BASE}/ko/app`, { waitUntil: 'networkidle' })
  await page.locator('.samples button').first().click()
  await page.waitForSelector('.block')
  await page.getByRole('tab', { name: '말로 고치기' }).click()
  await page.waitForSelector('.chat-examples button')
  ok('chat tab shows examples', (await page.locator('.chat-examples button').count()) === 3)
  const waitReply = async (n) => page.waitForFunction((count) => document.querySelectorAll('.chat-entry.is-assistant:not(.is-thinking), .chat-entry.is-error').length >= count, n, { timeout: 240000 })
  const blockTexts = () => page.locator('.block').allInnerTexts()

  let t0 = Date.now()
  await page.locator('.chat-input textarea').fill("제목을 '아침 루틴'으로 바꿔 줘")
  await page.locator('.chat-input textarea').press('Enter')
  await waitReply(1)
  const first = ((Date.now() - t0) / 1000).toFixed(1)
  const reply1 = await page.locator('.chat-entry.is-assistant').last().innerText()
  ok('title changed by chat', (await blockTexts()).some((text) => text.includes('아침 루틴')), `${first}s reply「${reply1.replace(/\n/g, ' ')}」`)

  t0 = Date.now()
  const before = await page.locator('.swatch.is-on').innerText()
  await page.locator('.chat-examples button').count() // examples hidden after first message
  await page.locator('.chat-input textarea').fill('도쿄 스타일로 바꿔 줘')
  await page.locator('.chat-input button[type=submit]').click()
  await waitReply(2)
  const second = ((Date.now() - t0) / 1000).toFixed(1)
  const after = await page.locator('.swatch.is-on').innerText()
  ok('theme changed by chat', after.includes('도쿄'), `${second}s ${before} → ${after}`)
  await page.screenshot({ path: `${OUT}/chat-ko.png` })

  await page.locator('.chat-undo').click()
  await page.waitForTimeout(400)
  ok('undo restores theme', (await page.locator('.swatch.is-on').innerText()) === before && (await page.locator('.chat-entry small').last().innerText()) === '되돌렸어요.')

  t0 = Date.now()
  await page.locator('.chat-input textarea').fill('숫자를 50%로 바꾸고 이름표를 2초 늦게 나오게 해 줘')
  await page.locator('.chat-input textarea').press('Enter')
  await waitReply(3)
  const third = ((Date.now() - t0) / 1000).toFixed(1)
  ok('two changes at once', (await blockTexts()).some((text) => text.includes('50')), `${third}s ${(await page.locator('.chat-entry.is-assistant').last().innerText()).replace(/\n/g, ' ')}`)

  t0 = Date.now()
  await page.locator('.chat-input textarea').fill('오늘 날씨 어때?')
  await page.locator('.chat-input textarea').press('Enter')
  await waitReply(4)
  ok('off-topic gets a reply without changes', true, `${((Date.now() - t0) / 1000).toFixed(1)}s ${(await page.locator('.chat-entry').last().innerText()).replace(/\n/g, ' ')}`)
  ok('saved after chat edits', /저장/.test(await page.locator('.ed-save').innerText()), await page.locator('.ed-save').innerText())
  ok('no console errors', errors.length === 0, errors.join(' | '))
  await page.screenshot({ path: `${OUT}/chat-ko-2.png` })
  console.log(results.join('\n'))
  await browser.close()
})()
